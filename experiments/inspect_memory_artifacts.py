"""Read saved baseline memory and join LoCoMo errors to official evidence turns.

This is an inspection tool, not an evaluator. It assigns no semantic failure
labels and changes neither memories nor benchmark scores. Run in the LightMem
environment to deserialize the locally generated Qdrant PointStruct records.
"""

import argparse
from collections import Counter
import json
from pathlib import Path
import pickle
import sqlite3


def read_jsonl(path):
    with path.open(encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def read_points(path):
    # Only deserialize trusted artifacts generated by our own baseline runs.
    with sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True) as db:
        for (blob,) in db.execute("SELECT point FROM points"):
            point = pickle.loads(blob)
            yield {"id": str(point.id), "payload": point.payload}


def inspect_memories(root, output_dir):
    summary = {"results_root": str(root), "lightmem": {}, "mem0": {}}
    with (output_dir / "memory_records.jsonl").open("w", encoding="utf-8") as stream:
        for method in ("lightmem", "mem0"):
            for task_dir in sorted((root / method).iterdir()):
                if not (task_dir / "efficiency.jsonl").exists():
                    continue
                counts = Counter()
                pattern = (
                    "lightmem_indices/*/collection/*/storage.sqlite"
                    if method == "lightmem"
                    else "mem0_indices/*/collection/mem0/storage.sqlite"
                )
                stores = sorted(task_dir.glob(pattern))
                for path in stores:
                    group_id = path.parents[2].name
                    for point in read_points(path):
                        payload = point["payload"]
                        counts["entries"] += 1
                        if method == "lightmem":
                            counts["consolidated_true"] += payload.get("consolidated") is True
                            counts["nonempty_update_queue"] += bool(payload.get("update_queue"))
                        stream.write(json.dumps({
                            "method": method, "task": task_dir.name,
                            "group_id": group_id, **point,
                        }, ensure_ascii=False) + "\n")
                result = {"stores": len(stores), **dict(counts)}
                if method == "lightmem":
                    operations = Counter()
                    for record in read_jsonl(task_dir / "efficiency.jsonl"):
                        stats = record["generator_statistics_after_build"]["lightmem_token_statistics"]
                        for operation, usage in stats["llm"].items():
                            operations[operation] += usage["calls"]
                    result["recorded_llm_calls"] = dict(operations)
                else:
                    history = task_dir / "mem0_runtime" / "history.db"
                    with sqlite3.connect(history.resolve().as_uri() + "?mode=ro", uri=True) as db:
                        result["recorded_history_events"] = dict(db.execute(
                            "SELECT event, COUNT(*) FROM history GROUP BY event"
                        ))
                summary[method][task_dir.name] = result
    return summary


def locomo_traces(root, data_path, output_path):
    with data_path.open(encoding="utf-8") as stream:
        conversations = json.load(stream)
    methods = ("bm25", "dense", "lightmem", "hipporag2", "mem0")
    retrieval, predictions = {}, {}
    for method in methods:
        task = root / method / "LoCoMo"
        retrieval[method] = {r["case"]["case_id"]: r for r in read_jsonl(task / "retrieval.jsonl")}
        predictions[method] = {
            p.parent.name: {r["case_id"]: r for r in read_jsonl(p)}
            for p in sorted((task / "evaluations").glob("*/predictions.jsonl"))
        }
    count = 0
    with output_path.open("w", encoding="utf-8") as stream:
        for sample in conversations:
            conversation = sample["conversation"]
            turns = {}
            for session, items in conversation.items():
                if not isinstance(items, list):
                    continue
                for turn in items:
                    turns[turn["dia_id"]] = {
                        "session_date_time": conversation[session + "_date_time"], **turn,
                    }
            for index, qa in enumerate(sample["qa"]):
                case_id = f"{sample['sample_id']}-{index}"
                evidence_ids = qa.get("evidence", [])
                record = {
                    "case_id": case_id, "official_qa": qa,
                    "official_evidence_turns": [turns[i] for i in evidence_ids if i in turns],
                    "unresolved_official_evidence_ids": [i for i in evidence_ids if i not in turns],
                    "methods": {},
                }
                for method in methods:
                    record["methods"][method] = {
                        "retrieved": retrieval[method][case_id]["retrieved"],
                        "evaluations": {
                            evaluator: {k: records[case_id][k] for k in ("prediction", "metrics")}
                            for evaluator, records in predictions[method].items()
                        },
                    }
                stream.write(json.dumps(record, ensure_ascii=False) + "\n")
                count += 1
    return count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-root", type=Path, required=True)
    parser.add_argument("--locomo-data", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    summary = inspect_memories(args.results_root, args.output_dir)
    summary["locomo_traced_questions"] = locomo_traces(
        args.results_root, args.locomo_data, args.output_dir / "locomo_case_traces.jsonl"
    )
    (args.output_dir / "memory_inspection_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
